def volatility(returns):
    mean = sum(returns) / len(returns)
    squares = 0
    for r in returns:
        squares = squares + (r - mean) ** 2
    return math.sqrt(squares / (len(returns) - 1))


def mix_of_first(funds, k):
    mix = []
    for month in range(len(funds[0])):
        total = 0
        for fund in funds[:k]:
            total = total + fund[month]
        mix.append(total / len(funds))
    return mix


for k in range(1, len(funds) + 1):
    print(f"{k} of {len(funds)}: {volatility(mix_of_first(funds, k)):.2%}")
